"""Run in the QGIS console to load candidate vectors; source rasters stay unchanged.

Locate this checkout through the loaded local rasters or current working folder.
No project CRS is changed and no files are exported. Labels are rover-pose
proxies associated with drill targets, not the exact drill-hole coordinates.
"""

import json
from pathlib import Path

from qgis.PyQt.QtCore import QVariant
from qgis.PyQt.QtGui import QColor, QFont
from qgis.core import (
    QgsCoordinateReferenceSystem, QgsFeature, QgsField, QgsFillSymbol,
    QgsGeometry, QgsLineSymbol, QgsMarkerSymbol, QgsPalLayerSettings,
    QgsPointXY, QgsProject, QgsTextBufferSettings,
    QgsTextFormat, QgsVectorLayer, QgsVectorLayerSimpleLabeling,
)
from qgis.utils import iface


def load_candidate():
    project = QgsProject.instance()
    starts = [Path.cwd()]
    starts.extend(Path(layer.source().split("|")[0]).parent
                  for layer in project.mapLayers().values()
                  if layer.source().lower().split("|")[0].endswith((".img", ".jp2")))
    report_path = None
    for start in starts:
        for parent in [start, *start.parents]:
            candidate = parent / "docs/terrain/pahrump-hills-aoi.json"
            if candidate.is_file():
                report_path = candidate
                break
        if report_path is not None:
            break
    if report_path is None:
        raise RuntimeError("Load a raster from this checkout's data/raw/pahrump-hills folder first")

    data = json.loads(report_path.read_text(encoding="utf-8"))
    crs = QgsCoordinateReferenceSystem()
    if not crs.createFromWkt(data["crs_wkt"]):
        raise RuntimeError("Could not create the candidate Mars CRS")

    # Remove only previous temporary layers generated by this helper on rerun.
    for layer in list(project.mapLayers().values()):
        if layer.customProperty("marswalk/pahrump_aoi_preview", False):
            project.removeMapLayer(layer.id())

    def layer_for(geometry_type, name):
        layer = QgsVectorLayer(geometry_type, name, "memory")
        if not layer.isValid():
            raise RuntimeError("Could not create preview vector layer")
        layer.setCrs(crs)
        layer.setCustomProperty("marswalk/pahrump_aoi_preview", True)
        return layer

    xmin, ymin, xmax, ymax = data["bounds_xy_m"]
    aoi = layer_for("Polygon", "Pahrump Hills - CANDIDATE 1000 x 1000 m")
    polygon = QgsFeature()
    polygon.setGeometry(QgsGeometry.fromPolygonXY([[QgsPointXY(xmin, ymin),
        QgsPointXY(xmax, ymin), QgsPointXY(xmax, ymax), QgsPointXY(xmin, ymax), QgsPointXY(xmin, ymin)]]))
    aoi.dataProvider().addFeatures([polygon])
    aoi.renderer().setSymbol(QgsFillSymbol.createSimple({
        "style": "no", "outline_color": "255,110,60,255", "outline_width": "0.8"}))
    aoi.updateExtents()
    project.addMapLayer(aoi)

    route = layer_for("MultiLineString", "NASA Curiosity traverse - spatial subset, all available sols")
    line = QgsFeature()
    line.setGeometry(QgsGeometry.fromMultiPolylineXY([
        [QgsPointXY(*point) for point in segment] for segment in data["traverse_segments_xy_m"]]))
    route.dataProvider().addFeatures([line])
    route.renderer().setSymbol(QgsLineSymbol.createSimple({"line_color": "255,210,65,255", "line_width": "0.55"}))
    route.updateExtents()
    project.addMapLayer(route)

    targets = layer_for("Point", "Science targets - associated rover poses, not drill holes")
    provider = targets.dataProvider()
    provider.addAttributes([QgsField("label", QVariant.String), QgsField("rmc", QVariant.String),
                            QgsField("drill_sol", QVariant.Int), QgsField("coordinate_role", QVariant.String)])
    targets.updateFields()
    features = []
    for item in data["science_target_rover_proxies"]:
        feature = QgsFeature(targets.fields())
        feature.setGeometry(QgsGeometry.fromPointXY(QgsPointXY(*item["xy_m"])))
        feature.setAttributes([item["name"] + " (rover " + item["rmc"] + ")", item["rmc"],
                               item["drill_sol"], item["coordinate_role"]])
        features.append(feature)
    provider.addFeatures(features)
    targets.renderer().setSymbol(QgsMarkerSymbol.createSimple({
        "name": "circle", "color": "60,220,245,255", "outline_color": "0,0,0,255", "size": "3"}))
    text_format = QgsTextFormat()
    text_format.setFont(QFont("Arial", 10))
    text_format.setSize(10)
    text_format.setColor(QColor("white"))
    buffer = QgsTextBufferSettings()
    buffer.setEnabled(True)
    buffer.setColor(QColor("black"))
    buffer.setSize(1)
    text_format.setBuffer(buffer)
    settings = QgsPalLayerSettings()
    settings.fieldName = "label"
    settings.setFormat(text_format)
    targets.setLabeling(QgsVectorLayerSimpleLabeling(settings))
    targets.setLabelsEnabled(True)
    targets.updateExtents()
    project.addMapLayer(targets)

    # Zoom using the layer CRS so QGIS transforms to the existing canvas CRS.
    iface.setActiveLayer(aoi)
    iface.zoomToActiveLayer()
    iface.mapCanvas().refresh()
    print("Loaded candidate AOI, official traverse subset, and three rover-pose proxies.")
    print("Bounds in Mars projected metres:", data["bounds_xy_m"])
    print("Candidate only: georeferencing alignment remains unresolved. No rasters modified.")


load_candidate()
